func TestAnalyzeCacheReusesAndClears(t *testing.T) {
	t.Parallel()

	dir := writeTree(t, map[string]string{"a.go": "package a\n"})

	first, err := analyze(context.Background(), dir)
	if err != nil {
		t.Fatalf("analyze: %v", err)
	}

	ClearCache()

	second, err := analyze(context.Background(), dir)
	if err != nil {
		t.Fatalf("analyze after clear: %v", err)
	}

	if first == second {
		t.Error("expected a fresh project after ClearCache, got the cached instance")
	}
}
