package v4

import (
	"fmt"
	"slices"
	"strings"
)

// referenceClassOrder fixes the section order of the generated reference so
// it is byte-stable across runs and machines.
var referenceClassOrder = []string{ //nolint:gochecknoglobals // fixed section order; the generated reference must be byte-stable
	"flag",
	"config",
	"command",
	"service",
	"output",
	"audit",
	"exit_code",
	"doctor",
	"editor",
}

// Reference markers bracket the generated section of docs/ERROR_REFERENCE.md.
const (
	errorRefBegin = "<!-- BEGIN GENERATED:SENTINEL-TABLE -->"
	errorRefEnd   = "<!-- END GENERATED:SENTINEL-TABLE -->"
)

// GenerateErrorReference renders the sentinel table for docs/ERROR_REFERENCE.md
// from the canonical sentinel fact table (see sentinelFacts), grouped by
// class in a fixed order. Everything between the generated-section markers in
// that file comes from here; a drift test fails when the committed doc stops
// matching this output, so the reference cannot lie about the code.
func GenerateErrorReference() string {
	facts := sentinelFacts()

	var b strings.Builder

	b.WriteString(errorRefBegin + "\n")
	b.WriteString(
		"<!-- Generated by v4.GenerateErrorReference from the canonical sentinel fact table (errors_facts.go). -->\n",
	)
	b.WriteString(
		"<!-- Do not edit between the markers; regenerate with: go test ./pkg/cmdguard/v4 -run TestErrorReferenceDoc -update-golden -->\n",
	)
	fmt.Fprintf(
		&b,
		"\n%d sentinels. Every row carries a stable machine code (`errors.Is`-reachable via `ErrorCode(err)` and emitted as `error_code` in the JSON error envelope), the Go sentinel, the envelope class, the sentinel message, and the actionable hint (`ErrorHint(err)`).\n",
		len(facts),
	)

	for _, class := range referenceClassOrder {
		rows := make([]sentinelFact, 0, len(facts))
		for _, fact := range facts {
			if fact.class == class {
				rows = append(rows, fact)
			}
		}

		if len(rows) == 0 {
			continue
		}

		slices.SortFunc(rows, func(a, b sentinelFact) int {
			return strings.Compare(a.code, b.code)
		})

		fmt.Fprintf(&b, "\n### %s errors\n\n", class)

		b.WriteString("| Code | Sentinel | Message | Hint |\n")
		b.WriteString("| --- | --- | --- | --- |\n")

		for _, row := range rows {
			fmt.Fprintf(&b, "| `%s` | `%s` | `%s` | %s |\n", row.code, row.name, row.match, row.hint)
		}
	}

	b.WriteString("\n" + errorRefEnd)

	return b.String()
}
